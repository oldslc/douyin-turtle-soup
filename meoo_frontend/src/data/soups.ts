/** 获取随机汤底 */
export function getRandomSoup(): SoupData {
  const index = Math.floor(Math.random() * SOUPS.length);
  return SOUPS[index];
}

/** 根据ID获取汤底 */
export function getSoupById(id: string): SoupData | undefined {
  return SOUPS.find((soup) => soup.id === id);
}
